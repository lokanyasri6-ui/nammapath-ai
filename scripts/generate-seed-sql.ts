/**
 * Generates supabase/seed.sql from the TypeScript seed (single source of truth).
 * Run: npm run seed:sql
 */
import fs from "node:fs";
import path from "node:path";
import { buildSeedGraph, buildSeedReports } from "../src/lib/seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const g = buildSeedGraph();
const reports = buildSeedReports();
const out: string[] = [
  "-- =====================================================================",
  "-- NammaPath AI — SYNTHETIC DEMONSTRATION DATA (generated by scripts/generate-seed-sql.ts)",
  "-- Every row is labelled origin = 'synthetic_demo'. Do not present as verified local data.",
  "-- Timestamps are relative to when this file was generated; re-generate before a demo.",
  "-- =====================================================================",
  "begin;",
  "delete from public.barrier_reports where origin = 'synthetic_demo';",
  "delete from public.pedestrian_segments where origin = 'synthetic_demo';",
  "delete from public.pedestrian_nodes where origin = 'synthetic_demo';",
];
for (const n of g.nodes) {
  out.push(
    `insert into public.pedestrian_nodes (id, name, name_ta, lat, lng, kind, selectable, origin) values (${[n.id, n.name, n.nameTa, n.lat, n.lng, n.kind, n.selectable, "synthetic_demo"].map(q).join(", ")});`,
  );
}
for (const s of g.segments) {
  out.push(
    `insert into public.pedestrian_segments (id, from_node, to_node, via, name, steps, ramp, surface, width_m, slope_pct, safe_crossing, tactile_paving, handrail, verification, origin, updated_at) values (${[
      s.id, s.from, s.to, s.via ?? null, s.name, s.steps, s.ramp, s.surface, s.widthM, s.slopePct, s.safeCrossing, s.tactilePaving, s.handrail, s.verification, s.origin, s.updatedAt,
    ].map(q).join(", ")});`,
  );
}
for (const r of reports) {
  out.push(
    `insert into public.barrier_reports (id, lat, lng, segment_id, category, severity, description, status, origin, ai_category, ai_severity, ai_confidence, ai_explanation, ai_uncertainty, ai_provider, ai_is_demo, user_corrected_ai, reporter_id, language, created_at, updated_at, last_verified_at) values (${[
      r.id, r.lat, r.lng, r.segmentId, r.category, r.severity, r.description, r.status, r.origin,
      r.ai?.category ?? null, r.ai?.severity ?? null, r.ai?.confidence ?? null, r.ai?.explanation ?? null, r.ai?.uncertainty ?? null, r.ai?.provider ?? null, r.ai?.isDemo ?? null,
      r.userCorrectedAi, r.reporterId, r.language, r.createdAt, r.updatedAt, r.lastVerifiedAt,
    ].map(q).join(", ")});`,
  );
  for (const v of r.votes) out.push(`insert into public.report_votes (report_id, client_id, action, created_at) values (${[r.id, v.clientId, v.action, v.at].map(q).join(", ")});`);
  for (const h of r.history) out.push(`insert into public.report_status_history (report_id, from_status, to_status, actor, note, created_at) values (${[r.id, h.from, h.to, h.by, h.note, h.at].map(q).join(", ")});`);
}
out.push("commit;", "");
const file = path.resolve(process.cwd(), "supabase/seed.sql");
fs.writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file} (${g.nodes.length} nodes, ${g.segments.length} segments, ${reports.length} reports)`);
